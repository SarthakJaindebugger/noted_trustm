import re

def clean_answer(text: str) -> str:
    """
    Remove all think tags and markdown fences, then return the cleaned answer.
    If nothing remains, return the default.
    """
    # Remove content between <think> and </think> (including both tags)
    text = re.sub(r'<think>.*?</think>', '', text, flags=re.DOTALL)
    # Remove any leftover <think> that has no closing tag (from tag to end)
    text = re.sub(r'<think>.*', '', text, flags=re.DOTALL)
    # Remove markdown code fences
    text = text.replace("```json", "").replace("```", "").strip()
    # If nothing is left, use the default
    if not text:
        text = "Not mentioned in transcript."
    return text


