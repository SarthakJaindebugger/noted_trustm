def load_embedder():
    global embed_model, tokenizer_emb
    if embed_model is None:
        tokenizer_emb = AutoTokenizer.from_pretrained(EMBED_MODEL_NAME)
        if tokenizer_emb.pad_token is None:
            tokenizer_emb.pad_token = tokenizer_emb.eos_token

        device = "cuda" if torch.cuda.is_available() else "cpu"
        print(f"Loading embedder on {device.upper()}...")
        embed_model = AutoModel.from_pretrained(EMBED_MODEL_NAME).to(device)
        embed_model.eval()
    return tokenizer_emb, embed_model

def unload_embedder():
    global embed_model, tokenizer_emb
    if embed_model is not None:
        if torch.cuda.is_available():
            embed_model.to("cpu")
            torch.cuda.empty_cache()
        del embed_model
        del tokenizer_emb
        embed_model = None
        tokenizer_emb = None
        gc.collect()
        print("Embedder unloaded and GPU memory freed")

def get_embedding(text):
    inputs = tokenizer_emb(text, return_tensors="pt", truncation=True, max_length=512, padding=True)
    inputs = {k: v.to(embed_model.device) for k, v in inputs.items()}
    with torch.no_grad():
        outputs = embed_model(**inputs)
    # Mean pooling over sequence length -> shape (batch, hidden_size)
    return outputs.last_hidden_state.mean(dim=1).cpu().float().numpy()[0].tolist()

